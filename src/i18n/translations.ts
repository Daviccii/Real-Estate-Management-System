/**
 * Central translation dictionaries for the PropNoxa frontend.
 *
 * Zero-dependency i18n: every user-facing chrome string in the translated
 * surface lives here under a flat dotted key. `en` is the fallback language;
 * `sw` (Kiswahili) is the first additional language for the Kenyan market.
 *
 * To translate a new area of the app:
 *   1. Use `<area>.<thing>` keys and add them to BOTH dictionaries below.
 *   2. In components, read `const { t } = useTranslation()` and render `t('key')`.
 *   3. The key-parity test (translations.test.ts) fails if en/sw drift apart,
 *      so a missing Swahili string is caught at test time, not in production.
 */

